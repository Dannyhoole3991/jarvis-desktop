"""
Deterministic strategy generator.

Turns (template, parameters) into the full source of a Freqtrade strategy.
There is no randomness and no model-written code here: the same inputs
always produce byte-identical source, so the registry's content hash is a
reliable identity and every backtest is reproducible.

Every generated strategy:
  - is long-only and unleveraged (can_short = False, no leverage callback),
  - has an explicit stoploss and NO ROI exit (exits are signal/stoploss only,
    so there is no hidden profit-taking behaviour),
  - consults the independent Risk Engine's gate file before any entry when
    JARVIS_RISK_GATE_FILE is set (paper trading). The gate can only veto.

The 'lookahead_control' template deliberately cheats (it reads the NEXT
candle). It exists only to prove that the lab's leakage detector catches
leakage; it is flagged as a control and never promoted.
"""

