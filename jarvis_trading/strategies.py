CONTROL_TEMPLATES = ("lookahead_control",) + V2.CONTROL_FAMILIES


def _block(lines):
    return "\n".join("        " + line for line in lines)


def canonical_params(template, overrides=None):
    if template in V2.FAMILIES:
        return V2.canonical_params(template, overrides)
    if template not in TEMPLATES:
        raise ValueError(f"Unknown template '{template}'. Known: {sorted(TEMPLATES)}")
    params = dict(TEMPLATES[template]["defaults"])
    params.update(overrides or {})
    return params


def class_name(template, params):
    digest = hashlib.sha256(json.dumps({"t": template, "p": params}, sort_keys=True).encode()).hexdigest()[:10]
    return f"JT_{digest}"


def generate(template, overrides=None):
    """Returns (class_name, source_code, params). Pure function of its inputs."""
    if template in V2.FAMILIES:
        return V2.generate(template, overrides)
    params = canonical_params(template, overrides)
    spec = TEMPLATES[template]
    name = class_name(template, params)
    source = BASE_TEMPLATE.format(
        template=template,
        params_literal=repr(json.dumps(params, sort_keys=True)),
        class_name=name,
        startup=spec["startup"],
        indicators=_block(spec["indicators"]),
        entry=_block(spec["entry"]),
        exit=_block(spec["exit"]),
    )
    return name, source, params


def hypothesis(template):
    if template in V2.FAMILIES:
        return V2.hypothesis(template)
    return TEMPLATES[template]["hypothesis"]


def all_templates():
    """Every template/family the lab knows, original six first."""
    return list(TEMPLATES) + list(V2.FAMILIES)


def research_templates():
    """The real research families (no controls): the original five plus the second-generation ones."""
    return [t for t in TEMPLATES if t not in CONTROL_TEMPLATES] + list(V2.RESEARCH_FAMILIES)
