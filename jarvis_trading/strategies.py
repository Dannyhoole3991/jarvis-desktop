def _risk_gate_allows():
    """Independent Risk Engine veto. No gate file configured -> not consulted (backtests)."""
    path = os.environ.get("JARVIS_RISK_GATE_FILE")
    if not path:
        return True
    try:
        with open(path, "r", encoding="utf-8") as f:
            return bool(json.load(f).get("allow_entries", False))
    except Exception:
        return False  # fail closed: if the gate is unreadable, do not enter


