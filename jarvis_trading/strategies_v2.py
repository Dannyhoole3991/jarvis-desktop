"""
Strategy families, second generation. Same guarantees as strategies.py
(deterministic source, long-only, spot, unleveraged, no hidden ROI exits,
independent Risk Engine gate consulted before every entry, fail-closed) plus:

  - multi-timeframe features through Freqtrade's @informative decorator, which
    shifts higher-timeframe candles so a daily value is only visible once that
    day has closed;
  - volatility / volume features;
  - adaptive position sizing that can only SHRINK a position (inverse
    volatility), and is encoded in the entry tag so it is computed
    vectorised from past candles and covered by the leakage detector;
  - signal-voting combinations;
  - the Risk Engine's `max_stake` is an additional cap on every stake.

A family is a parameter SPACE, not a strategy: `sample()` draws distinct
parameter sets from it with a seeded RNG, so a batch is reproducible. Nothing
here assumes any family works; the lab's gates decide.
"""

