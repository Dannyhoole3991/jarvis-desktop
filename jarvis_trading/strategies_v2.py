def _check(family):
    if family not in FAMILIES:
        raise ValueError(f"Unknown family '{family}'. Known: {sorted(FAMILIES)}")
    return FAMILIES[family]


def canonical_params(family, overrides=None):
    spec = _check(family)
    params = json.loads(json.dumps(spec["defaults"]))
    params.update(overrides or {})
    valid = spec.get("valid")
    if valid and not valid(params):
        raise ValueError(f"Invalid parameter combination for {family}: {params}")
    allowed = ("fixed", "inv_vol", "future_vol") if spec.get("control") else ("fixed", "inv_vol")
    if params.get("sizing") not in allowed:
        raise ValueError(f"sizing must be one of {allowed}")
    return params


def class_name(family, params):
    digest = hashlib.sha256(json.dumps({"t": family, "p": params}, sort_keys=True).encode()).hexdigest()[:10]
    return f"JT_{digest}"


def generate(family, overrides=None):
    """Returns (class_name, source, params). Pure function of its inputs."""
    spec = _check(family)
    params = canonical_params(family, overrides)
    name = class_name(family, params)
    informative = ""
    if spec.get("informative"):
        tf, lines = spec["informative"]
        body = "\n".join("        " + line for line in lines)
        informative = (f'\n    @informative("{tf}")\n    def populate_indicators_{tf}(self, dataframe: DataFrame, metadata: dict) -> DataFrame:\n'
                       f"{body}\n        return dataframe\n")
    source = BASE_V2.format(
        family=family, params_literal=repr(json.dumps(params, sort_keys=True)), class_name=name,
        startup=int(spec["startup"](params)), informative=informative,
        indicators="\n".join("        " + line for line in spec["indicators"]),
        entry=spec["entry"], exit=spec["exit"],
        sizing={"inv_vol": _SIZING_INV_VOL, "future_vol": _SIZING_FUTURE_VOL}.get(params["sizing"], _SIZING_FIXED))
    return name, source, params


def hypothesis(family):
    return _check(family)["hypothesis"]


def space_size(family):
    spec = _check(family)
    total = 1
    for choices in spec["space"].values():
        total *= len(choices)
    return total


def sample(family, n, seed=1, exclude=()):
    """
    n distinct valid parameter sets from the family's space, drawn with a seeded
    RNG (reproducible). `exclude` is a collection of canonical-JSON strings
    already tested. Returns a list of full parameter dicts.
    """
    spec = _check(family)
    keys = sorted(spec["space"])
    rng = random.Random(f"{family}:{seed}")
    seen = set(exclude)
    out = []
    total = space_size(family)
    attempts = 0
    while len(out) < n and attempts < max(2000, n * 50) and len(seen) < total + len(exclude):
        attempts += 1
        overrides = {k: rng.choice(spec["space"][k]) for k in keys}
        try:
            params = canonical_params(family, overrides)
        except ValueError:
            continue
        key = json.dumps(params, sort_keys=True)
        if key in seen:
            continue
        seen.add(key)
        out.append(params)
    return out
